#!/usr/bin/env python3
"""Генератор проекта KiCad: Voice-Unit - голосовой модуль прибора.

Мозг: ESP32-S3-WROOM-1-N16R8 (Wi-Fi/BT, 8 МБ octal-PSRAM) - тянет AEC
(эхоподавление), wake-word WakeNet и стриминг на бэкенд одновременно
(стек ESP-SR/ADF, как в колонках-референсах Espressif ESP32-S3-Box).
Звук: 2x ICS-43434 (I2S MEMS, преемник INMP441) по краям платы +
MAX98357A (3 Вт класс D, I2S) на ВЫНОСНОЙ динамик - микрофоны обязаны
жить далеко от динамика, иначе AEC бессилен (урок колонки M5Stack).
Питание: USB-C 5V (он же прошивка - у S3 родной USB), гребёнка 5V и
разъём 5V IN (JST) от внешней платы питания - батарейный блок вынесен
на отдельную плату (решение 2026-10-12: проще, взаимозаменяемо).
UART (3.3 В) к мозгам прибора H723/G474.

Назначение ног S3 (октальная PSRAM занимает IO35-37 - не трогаем):
  микрофоны I2S0 (общая шина на оба): WS=IO9 (п.17), SD=IO10 (п.18), SCK=IO11 (п.19)
  усилитель I2S1: SD_MODE=IO12 (п.20), DIN=IO13 (п.21), BCLK=IO14 (п.22), LRCLK=IO21 (п.23)
  UART к мозгам: п.36/37 (U0RXD/U0TXD); USB: IO19/IO20; LED=IO48, BOOT=IO0
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kicadenv
import pcbnew
import pcbhelp
from pcbhelp import Builder, mm, tomm, V, FPDIR
import kigen

OUT = sys.argv[1] if len(sys.argv) > 1 else "boards/Voice-Unit"
NAME = "Voice-Unit"
X0, X1, Y0, Y1 = 100.0, 160.0, 92.0, 134.0   # низ +10 мм: бывш. батарейная полоса, теперь резерв
BW, BH = X1 - X0, Y1 - Y0
CXB, CYB = (X0 + X1) / 2, (Y0 + Y1) / 2
FCU, BCU = pcbnew.F_Cu, pcbnew.B_Cu
W, WP = 0.25, 0.5

C0402 = ("Capacitor_SMD", "C_0402_1005Metric")
C0805 = ("Capacitor_SMD", "C_0805_2012Metric")
R0402 = ("Resistor_SMD", "R_0402_1005Metric")
HDRLIB = "Connector_PinHeader_2.54mm"
WROOM = ("RF_Module", "ESP32-S3-WROOM-1")
MIC = ("Sensor_Audio", "InvenSense_ICS-43434-6_3.5x2.65mm")
AMP = ("Package_DFN_QFN", "TQFN-16-1EP_3x3mm_P0.5mm_EP1.6x1.6mm")
SOT223 = ("Package_TO_SOT_SMD", "SOT-223-3_TabPin2")
USBC = ("Connector_USB", "USB_C_Receptacle_HRO_TYPE-C-31-M-12")
BTN = ("Button_Switch_SMD", "SW_SPST_SKQG_WithoutStem")
SOT23_6 = ("Package_TO_SOT_SMD", "SOT-23-6")

b = Builder(layers=2)

# ------------------------------------------------------------ размещение
# Расстановка ручная (KiCad, 2026-10-09, восстановлена из .history после
# того, как перегенерация её затёрла). Генератор не гонять без синка!
b.place("U1", WROOM[0], WROOM[1], 130.0, 103.5, 0, value="ESP32-S3-WROOM-1-N16R8")
b.place("MK1", MIC[0], MIC[1], 104.0, 120.5, 0, value="ICS-43434")
b.place("MK2", MIC[0], MIC[1], 156.0, 120.5, 0, value="ICS-43434")
b.place("U2", AMP[0], AMP[1], 114.75, 127.06, -90, value="MAX98357A")  # юг; I2S входят прямо: сверху и справа
b.place("U3", "Package_TO_SOT_SMD", "SOT-23-5", 113.55, 115.86, 90, value="TLV75733")   # LDO, падение <=0.425 В при 1 А
b.place("J1", USBC[0], USBC[1], 103.6, 105.68, 270, value="USB-C")   # ниже - подальше от H1
b.place("J2", HDRLIB, "PinHeader_1x02_P2.54mm_Vertical", 113.0, 131.5, 90, value="SPEAKER")
# крепёж: M2.5 (стандарт малых плат, как у Raspberry Pi), NPTH, вне BOM/монтажа
for _r, _x, _y in (("H1", 103.0, 94.6), ("H2", 157.0, 94.6), ("H3", 103.0, 131.4), ("H4", 157.0, 131.4)):
    b.place(_r, "MountingHole", "MountingHole_2.7mm_M2.5", _x, _y, 0, value="M2.5")
    b.fps[_r].Reference().SetVisible(False)                          # у края платы подпись не нужна
b.place("J4", HDRLIB, "PinHeader_1x04_P2.54mm_Vertical", 140.88, 131.5, 90, value="LOGIC")
b.place("SW1", BTN[0], BTN[1], 154.15, 103.4, 90, value="RESET")
b.place("SW2", BTN[0], BTN[1], 145.15, 108.9, -90, value="BOOT")
b.place("D3", "LED_SMD", "LED_0805_2012Metric", 151.5, 120.0, 90, value="LED")
# обвязка
b.place("R1", R0402[0], R0402[1], 152.0, 109.0, 90, value="10k")    # EN pullup, у RESET
b.place("C9", C0402[0], C0402[1], 116.52, 106.0, 180, value="1uF")  # EN RC
b.place("R2", R0402[0], R0402[1], 107.99, 124.5, 180, value="100k") # SD_MODE pulldown
b.place("R3", R0402[0], R0402[1], 138.49, 118.5, 0, value="1k")     # LED
b.place("R4", R0402[0], R0402[1], 114.49, 99.5, 180, value="5.1k")  # CC1
b.place("R5", R0402[0], R0402[1], 116.49, 110.0, 0, value="5.1k")   # CC2
# --- питание: батарейный блок (TP4057+MT3608+суперкап) вынесен на отдельную
# плату. Здесь только вход 5V: J3 (JST) -> D2 и USB VBUS -> D1 (диодное ИЛИ).
b.place("J3", "Connector_JST", "JST_PH_B4B-PH-K_1x04_P2.00mm_Vertical", 126.0, 130.0, 0, value="5V IN")
b.place("D2", "Diode_SMD", "D_SMA", 144.5, 121.0, 180, value="SS34")  # ORing: 5V IN -> +5V
b.place("D1", "Diode_SMD", "D_SMA", 144.5, 116.0, 180, value="SS34")  # ORing: VBUS -> +5V
b.place("C1", C0805[0], C0805[1], 155.05, 114.0, 180, value="10uF") # 3V3 у ESP32
b.place("C2", C0402[0], C0402[1], 118.6, 99.5, 90, value="100nF")    # 3V3 модуля: между выводами 2 и 1
b.place("C3", C0805[0], C0805[1], 110.0, 117.0, 180, value="10uF")  # вход LDO, вплотную к U3.IN
b.place("C4", C0402[0], C0402[1], 112.0, 126.98, 90, value="100nF")  # вплотную к VDD U2
b.place("C5", C0402[0], C0402[1], 110.85, 114.72, 180, value="1uF")  # выход LDO: даташит TLV757 >= 1 мкФ у OUT
b.place("C6", C0402[0], C0402[1], 158.2, 117.2, 0, value="100nF")    # MK2.VDD (ICS-43434: 0.1 мкФ у VDD)
b.place("C10", C0402[0], C0402[1], 106.4, 117.8, 180, value="100nF") # MK1.VDD
b.place("C7", C0805[0], C0805[1], 110.5, 127.0, 90, value="10uF")    # 5V, сразу за C4
b.place("C8", C0805[0], C0805[1], 116.5, 102.95, 90, value="10uF")

# ------------------------------------------------------------ схема
d = kigen.Design(NAME, "Voice-Unit: ESP32-S3, 2x I2S mic, 3W I2S amp, barge-in capable")
d.prepare()
d.add(kigen.Part("U1", "RF_Module:ESP32-S3-WROOM-1", "ESP32-S3-WROOM-1-N16R8",
                 "%s:%s" % WROOM,
                 {"1": "GND", "2": "+3V3", "3": "EN",
                  "17": "MIC_WS", "18": "MIC_SD", "19": "MIC_SCK",
                  "20": "AMP_SD", "21": "AMP_DIN", "22": "AMP_BCLK", "23": "AMP_LRCLK",
                  "13": "USB_DM", "14": "USB_DP",
                  "25": "LED_K", "27": "BOOT",
                  "36": "RX", "37": "TX",
                  "40": "GND", "41": "GND"}, at=(120, 80)))
# ICS-43434 (DS-000069, табл. 8): 1 WS, 2 LR, 3 GND, 4 SCK, 5 VDD, 6 SD.
# LR: MK1 = GND (левый канал), MK2 = 3V3 (правый). SD по даташиту требует
# 100k вниз - включаем встроенную подтяжку GPIO в прошивке.
d.add(kigen.Part("MK1", "Sensor_Audio:ICS-43434", "ICS-43434", "%s:%s" % MIC,
                 {"1": "MIC_WS", "2": "GND", "3": "GND", "4": "MIC_SCK",
                  "5": "+3V3", "6": "MIC_SD"}, at=(60, 80)))
d.add(kigen.Part("MK2", "Sensor_Audio:ICS-43434", "ICS-43434", "%s:%s" % MIC,
                 {"1": "MIC_WS", "2": "+3V3", "3": "GND", "4": "MIC_SCK",
                  "5": "+3V3", "6": "MIC_SD"}, at=(60, 130)))
# MAX98357A (TQFN-16): символа в KiCad нет - заглушка с теми же номерами 1-16.
# Реальная распиновка: 1 DIN, 2 GAIN, 4 SD_MODE, 7/8 VDD, 9 OUTP, 10 OUTN,
# 14 LRCLK, 16 BCLK, 3/11/15 GND; EP(17) на землю - прицеплен ниже вручную.
d.add(kigen.Part("U2", "74xx:74HC595", "MAX98357A", "%s:%s" % AMP,
                 {"1": "AMP_DIN", "4": "AMP_SD", "7": "+5V", "8": "+5V",
                  "9": "SPK+", "10": "SPK-", "14": "AMP_LRCLK", "16": "AMP_BCLK",
                  "3": "GND", "11": "GND", "15": "GND"}, at=(200, 80)))
# TLV75733 (SOT-23-5, DBV): 1 IN, 2 GND, 3 EN (на вход = всегда вкл), 4 NC, 5 OUT.
# Вместо AMS1117: тому нужно ~1.1 В запаса, а после SS34 от 5 В остаётся ~4.5 В.
d.add(kigen.Part("U3", "Regulator_Linear:TLV75733PDBV", "TLV75733", "Package_TO_SOT_SMD:SOT-23-5",
                 {"1": "+5V", "2": "GND", "3": "+5V", "5": "+3V3"}, at=(200, 140)))
USBC_LIBID = "Connector:USB_C_Receptacle_USB2.0_16P"
SHIELD = [p.number for p in kigen.get_symbol(USBC_LIBID).pins if p.name == "SHIELD"][0]
d.add(kigen.Part("J1", USBC_LIBID, "USB-C", "%s:%s" % USBC,
                 {"A1": "GND", "A12": "GND", "B1": "GND", "B12": "GND",
                  "A4": "VBUS", "A9": "VBUS", "B4": "VBUS", "B9": "VBUS",
                  "A5": "CC1", "B5": "CC2", "A6": "USB_DP", "B6": "USB_DP",
                  "A7": "USB_DM", "B7": "USB_DM", SHIELD: "GND"}, at=(280, 60)))
d.add(kigen.Part("J2", "Connector_Generic:Conn_01x02", "SPEAKER",
                 "%s:PinHeader_1x02_P2.54mm_Vertical" % HDRLIB,
                 {"1": "SPK+", "2": "SPK-"}, at=(280, 110)))
d.add(kigen.Part("J4", "Connector_Generic:Conn_01x04", "LOGIC",
                 "%s:PinHeader_1x04_P2.54mm_Vertical" % HDRLIB,
                 {"1": "+5V", "2": "GND", "3": "TX", "4": "RX"}, at=(280, 140)))
d.add(kigen.Part("SW1", "Switch:SW_Push", "RESET", "Button_Switch_SMD:SW_SPST_SKQG_WithoutStem",
                 {"1": "EN", "2": "GND"}, at=(280, 170)))
d.add(kigen.Part("SW2", "Switch:SW_Push", "BOOT", "Button_Switch_SMD:SW_SPST_SKQG_WithoutStem",
                 {"1": "BOOT", "2": "GND"}, at=(280, 195)))
d.add(kigen.Part("D3", "Device:LED", "LED", "LED_SMD:LED_0805_2012Metric",
                 {"1": "LED_KK", "2": "+3V3"}, at=(340, 60)))
d.add(kigen.Part("R1", "Device:R", "10k", "%s:%s" % R0402, {"1": "+3V3", "2": "EN"}, at=(340, 85)))
d.add(kigen.Part("C9", "Device:C", "1uF", "%s:%s" % C0402, {"1": "EN", "2": "GND"}, at=(340, 110)))
d.add(kigen.Part("R2", "Device:R", "100k", "%s:%s" % R0402, {"1": "AMP_SD", "2": "GND"}, at=(340, 135)))
d.add(kigen.Part("R3", "Device:R", "1k", "%s:%s" % R0402, {"1": "LED_K", "2": "LED_KK"}, at=(340, 160)))
d.add(kigen.Part("R4", "Device:R", "5.1k", "%s:%s" % R0402, {"1": "CC1", "2": "GND"}, at=(340, 185)))
d.add(kigen.Part("R5", "Device:R", "5.1k", "%s:%s" % R0402, {"1": "CC2", "2": "GND"}, at=(340, 210)))
# --- вход 5V от внешней платы питания: 4 пина, по 2 на плюс и минус
# (JST PH держит 2 А на контакт; парой - запас и меньше падение)
d.add(kigen.Part("J3", "Connector_Generic:Conn_01x04", "5V IN",
                 "Connector_JST:JST_PH_B4B-PH-K_1x04_P2.00mm_Vertical",
                 {"1": "VIN_EXT", "2": "VIN_EXT", "3": "GND", "4": "GND"}, at=(60, 230)))
d.add(kigen.Part("D2", "Device:D_Schottky", "SS34", "Diode_SMD:D_SMA",
                 {"1": "+5V", "2": "VIN_EXT"}, at=(120, 230)))
d.add(kigen.Part("D1", "Device:D_Schottky", "SS34", "Diode_SMD:D_SMA",
                 {"1": "+5V", "2": "VBUS"}, at=(170, 230)))
d.add(kigen.Part("C1", "Device:C", "10uF", "%s:%s" % C0805, {"1": "+3V3", "2": "GND"}, at=(380, 85)))
d.add(kigen.Part("C2", "Device:C", "100nF", "%s:%s" % C0402, {"1": "+3V3", "2": "GND"}, at=(380, 110)))
d.add(kigen.Part("C3", "Device:C", "10uF", "%s:%s" % C0805, {"1": "+5V", "2": "GND"}, at=(380, 135)))
d.add(kigen.Part("C4", "Device:C", "100nF", "%s:%s" % C0402, {"1": "+5V", "2": "GND"}, at=(380, 160)))
d.add(kigen.Part("C5", "Device:C", "1uF", "%s:%s" % C0402, {"1": "+3V3", "2": "GND"}, at=(380, 185)))
d.add(kigen.Part("C6", "Device:C", "100nF", "%s:%s" % C0402, {"1": "+3V3", "2": "GND"}, at=(380, 210)))
d.add(kigen.Part("C10", "Device:C", "100nF", "%s:%s" % C0402, {"1": "+3V3", "2": "GND"}, at=(380, 235)))
d.add(kigen.Part("C7", "Device:C", "10uF", "%s:%s" % C0805, {"1": "+5V", "2": "GND"}, at=(420, 60)))
d.add(kigen.Part("C8", "Device:C", "10uF", "%s:%s" % C0805, {"1": "+3V3", "2": "GND"}, at=(420, 85)))
for i, _h in enumerate(["H1", "H2", "H3", "H4"]):
    d.add(kigen.Part(_h, "Mechanical:MountingHole", "M2.5", "MountingHole:MountingHole_2.7mm_M2.5",
                     {}, at=(500 + 25 * i, 200)))
for i, n in enumerate(["GND", "+3V3", "+5V", "VBUS", "VIN_EXT"]):
    d.add(kigen.Part("#FLG%d" % i, "power:PWR_FLAG", "PWR_FLAG", "", {"1": n}, at=(460, 60 + 22 * i)))

os.makedirs(OUT, exist_ok=True)
for _pt in d.parts:
    if ":" in _pt.footprint:
        _pt.footprint = "auto_probe:" + _pt.footprint.split(":", 1)[1]
d.write_sch(os.path.join(OUT, NAME + ".kicad_sch"))
for p in d.parts:
    if p.ref.startswith("#"):
        continue
    for pn, net in p.nets.items():
        try:
            b.setnet(p.ref, pn, net)
        except KeyError:
            pass
# LED: катодная цепочка через R3 - у LED в схеме 1=K: фактически K->R3->IO48.
# Проще на плате: LED_K это IO48, LED_KK - узел между R3 и LED... пока скелет.
# EP усилителя (пад 17) - на землю, в символе-заглушке его нет:
try:
    b.setnet("U2", "17", "GND")
except KeyError:
    pass

# ============================================================== разводка
# Заход 1: питание. GND - зонами. Сигналы (USB, I2S, UART, EN/BOOT) - заход 2.
WV = 0.35   # VBUS: ток заряда + ESP, 0.35 мм хватает
# --- VBUS: J1 (верхняя пара падов) -> верхом -> запад-столб x112.35
b.track("VBUS", [(107.64, 103.23), (109.0, 103.23), (109.8, 102.78)], FCU, WV)
b.via("VBUS", 109.8, 102.78)
b.track("VBUS", [(109.8, 102.78), (109.0, 111.18)], BCU, WV)                     # B: вниз вдоль USB
b.track("VBUS", [(109.0, 111.18), (120.0, 116.5), (139.8, 116.3), (139.8, 116.1)], BCU, WV)
b.via("VBUS", 139.8, 116.1)
b.track("VBUS", [(139.8, 116.1), (141.5, 116.0), (142.5, 116.0)], FCU, WV)       # -> D1.2
# --- +5V: диоды -> J4.1, юг-магистраль; запад через B
b.track("+5V", [(146.5, 116.0), (146.5, 127.5), (142.0, 130.6), (140.88, 131.5)], FCU, WP)
b.track("+5V", [(146.5, 125.8), (119.8, 125.8)], FCU, WP)                        # южная магистраль
b.via("+5V", 120.0, 125.8)
b.track("+5V", [(120.0, 125.8), (121.5, 124.3), (121.5, 117.15), (116.4, 117.15),
                (115.4, 118.2)], BCU, WP)                                        # B: к U3 в обход юга
b.via("+5V", 115.4, 118.2)
b.track("+5V", [(115.4, 118.2), (112.6, 118.2), (112.6, 117.0)], FCU, WP)        # -> U3.IN снизу
b.track("+5V", [(114.5, 118.2), (114.5, 117.0)], FCU, W)                         # -> U3.EN (всегда вкл)
b.track("+5V", [(112.6, 117.0), (110.95, 117.0)], FCU, WP)                       # U3.IN -> C3.1 вплотную
b.track("GND", [(113.55, 117.0), (113.55, 115.86), (115.6, 115.86)], FCU, W)     # U3.GND между рядами -> виа
b.via("GND", 115.9, 115.86)
b.track("GND", [(110.37, 114.72), (110.0, 115.75)], FCU, W)                      # C5.2 -> виа
b.track("GND", [(109.05, 117.0), (109.6, 116.2), (110.0, 115.75)], FCU, W)       # C3.2 -> виа
b.via("GND", 110.0, 115.75)
# --- VIN_EXT: J3 пины 1+2 -> по B в пад D2.2 (до 1.4 А - широкая)
WI = 0.8
b.track("VIN_EXT", [(126.0, 130.0), (128.0, 130.0)], FCU, WI)                    # пары падов J3
b.track("VIN_EXT", [(126.0, 130.0), (126.0, 128.6), (127.5, 127.1), (139.6, 127.1),
                    (142.5, 124.2), (142.5, 123.1)], BCU, WI)
b.via("VIN_EXT", 142.5, 123.1)                                                   # под D2.2, вне корпуса
b.track("VIN_EXT", [(142.5, 123.1), (142.5, 121.0)], FCU, WI)                    # -> D2.2
b.track("GND", [(130.0, 130.0), (132.0, 130.0)], FCU, WI)                        # пары падов J3
# --- +3V3: U3.OUT -> на восток южнее R5 -> по B в восточный хвост под модулем;
# от той же точки вверх по F к C8 и U1.2 (колонны на север больше нет - она
# перекрывала CC-резисторам дорогу к USB)
b.track("+3V3", [(112.6, 114.72), (112.6, 113.9), (113.4, 113.1), (115.3, 111.2),
                 (118.6, 111.2)], FCU, WP)                                       # U3.OUT -> восток
b.via("+3V3", 118.6, 111.3)
b.track("+3V3", [(118.6, 111.2), (118.6, 111.3)], FCU, WP)
b.track("+3V3", [(118.6, 111.3), (118.4, 112.6)], BCU, WP)                       # B: в хвост
b.track("+3V3", [(118.6, 111.2), (118.6, 103.9), (119.6, 102.9), (119.6, 99.51),
                 (121.25, 99.51)], FCU, W)                                       # -> U1.2 снизу
b.track("+3V3", [(118.6, 103.9), (117.0, 103.9)], FCU, W)                        # -> C8.1
b.track("+3V3", [(118.4, 112.6), (150.3, 113.0), (150.3, 113.3)], BCU, WP)       # B: восточный хвост
b.via("+3V3", 150.3, 113.3)
b.track("+3V3", [(150.3, 113.3), (150.3, 110.9), (151.2, 110.3), (154.9, 110.3)], FCU, W)
b.track("+3V3", [(152.0, 110.3), (152.0, 109.51)], FCU, W)                       # -> R1.1
b.track("+3V3", [(154.9, 110.3), (156.3, 110.3), (156.3, 112.9), (156.15, 113.2)], FCU, W)  # -> C1.1
b.track("+3V3", [(112.6, 114.72), (111.33, 114.72)], FCU, W)                    # U3.OUT -> C5.1 вплотную
# --- EN: RESET + R1 на востоке, северный коридор -> U1.3; к C9 по B из-под модуля
